#变量，即x，给某个事物定一个x名称，用来赋予值
# 1. 变量（就是给数据起个名字）
#作用：把数据存起来，方便后面用
#写法：名字 = 数据 
age = 18 #定义了一个age年龄，并且赋值是18 数据类型：整数
score = 95.5 #定义了一个score为分数，并且赋值 数据类型：小数
name = "小明" #定义一个字符串
city = "北京" #定义一个字符串
is_student = True #定义bool 并且为True
is_raining = False #定义bool 并且为False


# Python 最常用 4 种：
# int：整数（1, 100, -5）
# float：小数（99.9, 3.14）
# str：字符串（必须用双引号 / 单引号包起来）
# bool：布尔（只有 True / False
#type(变量)
print(type(age))
print(type(score))
print(type(name))
print(type(city))
print(type(is_student))
print(type(is_raining))


#输出
print((age))
print((score))
print((name))
print((city))
print((is_student))
print((is_raining))

